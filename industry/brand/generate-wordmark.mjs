// node industry/brand/generate-wordmark.mjs <@fontsource/noto-sans-sc package directory>
// Outline both lines in Noto Sans SC so font metrics and transparent margins cannot shift the lockup.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const pkg = process.argv[2];
if (!pkg) throw new Error("Pass the @fontsource/noto-sans-sc package directory.");
const fonts = new Map();
function fontFor(ch, weight) {
  const css = readFileSync(path.join(pkg, `${weight}.css`), "utf8");
  const faces = [...css.matchAll(/url\(\.\/files\/([\w-]+)\.woff2\)[^;]*;\s*unicode-range: ([^;]+);/g)].map((m) => ({
    file: `${m[1]}.woff`,
    ranges: m[2].split(",").map((r) => r.trim().replace("U+", "").split("-").map((h) => parseInt(h, 16))),
  }));
  const cp = ch.codePointAt(0);
  const face = faces.find((f) => f.ranges.some(([a, b]) => cp >= a && cp <= (b ?? a)));
  if (!face) throw new Error(`No font slice for ${ch}.`);
  if (!fonts.has(face.file)) {
    const buf = readFileSync(path.join(pkg, "files", face.file));
    fonts.set(face.file, opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)));
  }
  return fonts.get(face.file);
}

function line(text, weight, height, x, top, gap) {
  const glyphs = [...text].map((ch) => {
    const font = fontFor(ch, weight);
    return { ch, font, box: font.getPath(ch, 0, 0, 1000).getBoundingBox() };
  });
  const minY = Math.min(...glyphs.map(({ box }) => box.y1));
  const maxY = Math.max(...glyphs.map(({ box }) => box.y2));
  const scale = height / (maxY - minY);
  const paths = glyphs.map(({ ch, font, box }) => {
    const d = font.getPath(ch, x - box.x1 * scale, top - minY * scale, 1000 * scale).toPathData(2);
    x += (box.x2 - box.x1) * scale + gap;
    return d;
  });
  return { paths, right: x - gap };
}

// The 84-unit icon is taller than the 62-unit text group. Both are centred vertically at y=42.
// The two lines share both visible edges. Distribute the tagline by spacing, without stretching glyphs.
const title = line("气市观察", 500, 34, 0, 11, 4.5);
const taglineText = "关注气源与市场";
const taglineInk = line(taglineText, 400, 18, 0, 55, 0);
const taglineGap = (title.right - taglineInk.right) / ([...taglineText].length - 1);
const tagline = line(taglineText, 400, 18, 0, 55, taglineGap);
const titleX = 177 - title.right / 2;
const taglineX = titleX;
if (Math.max(title.right, tagline.right) > 150) throw new Error("Wordmark exceeds its text column.");
const icon = readFileSync(new URL("./logo.svg", import.meta.url), "utf8").replace(/<svg[^>]*>|<\/svg>/g, "").trim();
const svg = `<!-- Noto Sans SC Medium / Regular, SIL Open Font License 1.1. Generated by generate-wordmark.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 258 84" role="img" aria-label="气市观察，关注气源与市场">
  <defs>
    <g id="icon" transform="scale(0.1640625)">${icon}</g>
    <path id="ink" transform="translate(${titleX.toFixed(2)} 0)" d="${title.paths.slice(0, 2).join(" ")}"/>
    <path id="accent" transform="translate(${titleX.toFixed(2)} 0)" d="${title.paths.slice(2).join(" ")}"/>
    <path id="tagline" transform="translate(${taglineX.toFixed(2)} 0)" d="${tagline.paths.join(" ")}"/>
  </defs>
  <use href="#icon"/>
  <use href="#ink" fill="#202b30"/>
  <use href="#accent" fill="#176b75"/>
  <use href="#tagline" fill="#63737a"/>
</svg>
`;
writeFileSync(new URL("./wordmark.svg", import.meta.url), svg);
console.log({ viewBox: "0 0 258 84", titleX, taglineX, titleWidth: title.right, taglineWidth: tagline.right, taglineGap, verticalCentre: 42, bytes: Buffer.byteLength(svg) });
